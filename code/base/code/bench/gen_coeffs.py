"""Write coeffs.h for bench.cpp from ../../data/tableaux.json (double precision)."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, "..", "..", "data", "tableaux.json")))
METHODS = ["CRK5-opt", "CRK5-s", "CRK6-opt", "CRK6-s", "CCK6(5)", "DP5", "CK5", "Butcher6", "RK6-opt", "DP6(5)", "Verner6(5)"]
lines = ["// generated by gen_coeffs.py -- do not edit", "#pragma once", "#include <complex>",
         "struct Tab { const char* name; int s; bool cplx; bool fsal; double are[8][8]; double aim[8][8];"
         " double bre[8]; double bim[8]; double cre[8]; double cim[8]; };",
         f"static const int NMETH = {len(METHODS)};", "static const Tab TABS[NMETH] = {"]
for nm in METHODS:
    t = d[nm]; s = t["s"]
    A = t["A"]; b = t["b"][0]
    are = [[float(A[i][j][0]) if (i < s and j < i) else 0.0 for j in range(8)] for i in range(8)]
    for i in range(s, 8):
        are[i] = [0.0] * 8
    aim = [[float(A[i][j][1]) if (i < s and j < i) else 0.0 for j in range(8)] for i in range(8)]
    bre = [float(v[0]) for v in b] + [0.0] * (8 - s)
    bim = [float(v[1]) for v in b] + [0.0] * (8 - s)
    cre = [sum(are[i][:i]) for i in range(8)]
    cim = [sum(aim[i][:i]) for i in range(8)]
    fsal = (not t["projected"]) and all(abs(are[s - 1][j] - bre[j]) < 1e-15 for j in range(s - 1)) and abs(bre[s - 1]) < 1e-15
    f = lambda M: "{" + ",".join("{" + ",".join(repr(x) for x in row) + "}" for row in M) + "}"
    v = lambda x: "{" + ",".join(repr(y) for y in x) + "}"
    lines.append(f'  {{"{nm}", {s}, {"true" if t["projected"] else "false"}, {"true" if fsal else "false"}, '
                 f'{f(are)}, {f(aim)}, {v(bre)}, {v(bim)}, {v(cre)}, {v(cim)}}},')
lines.append("};")
open(os.path.join(HERE, "coeffs.h"), "w").write("\n".join(lines) + "\n")
print("wrote coeffs.h")
