"""Newer real pairs added to the comparison in R1 (review, Section 5, item 4).

  Tsit5(4)  Tsitouras 5(4), 7 stages, FSAL (6 evaluations per step) [Tsitouras 2011]
  BS5(4)    Bogacki--Shampine 5(4), 8 stages, FSAL (7 evaluations per step) [Bogacki, Shampine 1996]
  Vern6(5)  Verner's "most efficient" 6(5) pair, 9 stages, FSAL (8 evaluations per step) [Verner 2010]

Source of the coefficients: OrdinaryDiffEq.jl (SciML), files tsit_tableaus.jl (85-digit values of
Tsit5), low_order_rk_tableaus.jl (exact rationals of BS5) and verner_tableaus.jl (exact rationals of
Vern6, "from Verner's website").  The propagated solution is the higher-order one (the last row of A
for these FSAL pairs); the embedded weights are b + btilde in the notation of OrdinaryDiffEq.  For
BS5 only the embedded fourth-order formula on all eight stages is used: Bogacki and Shampine also
propose a second estimate, which the common controller of this paper does not use.

The order conditions are verified in 80-digit arithmetic when the module is run; Tsit5 satisfies them
to the precision of its 85-digit coefficients.  Writes R1/data/tableaux_r1.json in the format of
data/tableaux.json (read by tableaux.load_refined).
"""
