"""Write coeffs.h for bench.cpp from data/tableaux.json (double precision).

The R1 folder has no tableaux.json of its own (the coefficients did not change), so the file of the
original submission, ../../../data/tableaux.json, is used when R1/data/tableaux.json is absent.  The real
pairs added in R1 (Tsit5(4), BS5(4), Vern6(5)) are read from R1/data/tableaux_r1.json.  Tableaux have at
most SMAX = 10 stages (Vern6(5) has nine).
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = [os.path.join(HERE, "..", "..", "data", "tableaux.json"), os.path.join(HERE, "..", "..", "..", "data", "tableaux.json")]
d = json.load(open(next(x for x in SRC if os.path.exists(x))))
d.update(json.load(open(os.path.join(HERE, "..", "..", "data", "tableaux_r1.json"))))
METHODS = ["CRK5-opt", "CRK5-s", "CRK6-opt", "CRK6-s", "CCK6(5)", "DP5", "CK5", "Tsit5(4)", "BS5(4)",
           "Butcher6", "RK6-opt", "DP6(5)", "Verner6(5)", "Vern6(5)"]
SMAX = 10
lines = ["// generated by gen_coeffs.py -- do not edit", "#pragma once", "#include <complex>",
         f"static const int SMAX = {SMAX};",
         "struct Tab { const char* name; int s; bool cplx; bool fsal; double are[SMAX][SMAX]; double aim[SMAX][SMAX];"
         " double bre[SMAX]; double bim[SMAX]; double cre[SMAX]; double cim[SMAX]; };",
         f"static const int NMETH = {len(METHODS)};", "static const Tab TABS[NMETH] = {"]
for nm in METHODS:
    t = d[nm]; s = t["s"]
    A = t["A"]; b = t["b"][0]
    are = [[float(A[i][j][0]) if (i < s and j < i) else 0.0 for j in range(SMAX)] for i in range(SMAX)]
    for i in range(s, SMAX):
        are[i] = [0.0] * SMAX
    aim = [[float(A[i][j][1]) if (i < s and j < i) else 0.0 for j in range(SMAX)] for i in range(SMAX)]
    bre = [float(v[0]) for v in b] + [0.0] * (SMAX - s)
    bim = [float(v[1]) for v in b] + [0.0] * (SMAX - s)
    cre = [sum(are[i][:i]) for i in range(SMAX)]
    cim = [sum(aim[i][:i]) for i in range(SMAX)]
    fsal = (not t["projected"]) and all(abs(are[s - 1][j] - bre[j]) < 1e-15 for j in range(s - 1)) and abs(bre[s - 1]) < 1e-15
    f = lambda M: "{" + ",".join("{" + ",".join(repr(x) for x in row) + "}" for row in M) + "}"
    v = lambda x: "{" + ",".join(repr(y) for y in x) + "}"
    lines.append(f'  {{"{nm}", {s}, {"true" if t["projected"] else "false"}, {"true" if fsal else "false"}, '
                 f'{f(are)}, {f(aim)}, {v(bre)}, {v(bim)}, {v(cre)}, {v(cim)}}},')
lines.append("};")
open(os.path.join(HERE, "coeffs.h"), "w").write("\n".join(lines) + "\n")
print("wrote coeffs.h")
