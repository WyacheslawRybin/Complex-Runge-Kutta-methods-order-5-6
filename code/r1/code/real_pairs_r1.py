mp.mp.dps = 90


def _mp(v):
    if isinstance(v, F):
        return mp.mpf(v.numerator) / v.denominator
    return mp.mpf(v)


def _tableau(name, s, a, b, bh, p, q, cost):
    A = [[_mp(a.get((i + 1, j + 1), 0)) for j in range(s)] for i in range(s)]
    lv = [(s, p, [_mp(v) for v in b]), (s, q, [_mp(v) for v in bh])]
    return Tableau(name, A, lv, projected=False, cost=cost)


