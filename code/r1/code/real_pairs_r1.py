def all_new():
    return {"Tsit5(4)": tsit5(), "BS5(4)": bs5(), "Vern6(5)": vern6()}


def _s(x):
    return mp.nstr(x, 80, strip_zeros=False)


def main():
    out = {}
    for name, T in all_new().items():
        res = T.residuals()
        rmax = [max(abs(v) for v in lev) for lev in res]
        E = [T.E(L) for L in range(len(T.levels))]
        fsal = all(T.A[-1][j] == T.levels[0][2][j] for j in range(T.s - 1)) and T.levels[0][2][-1] == 0
        print(f"{name:9s} s={T.s} cost={T.cost} FSAL={fsal} levels={[(m, p) for m, p, _ in T.levels]} "
              f"resid={[mp.nstr(r, 3) for r in rmax]} E={[mp.nstr(e, 6) for e in E]} "
              f"maxcoef={mp.nstr(T.maxcoef(), 6)} c={[mp.nstr(mp.re(c), 8) for c in T.c]}")
        assert fsal
        assert max(rmax) < mp.mpf(10) ** -75, rmax      # Tsit5: 80-digit btilde
        out[name] = dict(s=T.s, cost=T.cost, projected=False, levels=[[m, p] for m, p, _ in T.levels],
                         A=[[[_s(mp.re(T.A[i][j])), "0"] for j in range(i)] for i in range(T.s)],
                         b=[[[_s(mp.re(v)), "0"] for v in bb] for _, _, bb in T.levels],
                         E=[float(e) for e in E], maxcoef=float(T.maxcoef()),
                         resid=[float(r) for r in rmax])
    json.dump(out, open(os.path.join(R.DATA, "tableaux_r1.json"), "w"), indent=1)
    print("wrote data/tableaux_r1.json")


if __name__ == "__main__":
    main()
